const RULES = [
  // [正则, 替换模板]
  [/^barbell (.+)$/, (m) => '杠铃' + m[1]],
  [/^dumbbell (.+)$/, (m) => '哑铃' + m[1]],
  [/^cable (.+)$/, (m) => '绳索' + m[1]],
  [/^band (.+)$/, (m) => '弹力带' + m[1]],
  [/^kettlebell (.+)$/, (m) => '壶铃' + m[1]],
  [/^smith machine (.+)$/, (m) => '史密斯' + m[1]],
  [/^machine (.+)$/, (m) => '器械' + m[1]],
  [/^bodyweight (.+)$/, (m) => '自重' + m[1]],
  [/^weight (.+)$/, (m) => '负重' + m[1]],
];

// ─── 主翻译函数 ───
function translateName(en) {
  const cleaned = cleanName(en);
  const lower = cleaned.toLowerCase();

  // ① 完整短语命中
  if (PHRASE[lower]) return PHRASE[lower];

  // ①-b 连字符变体命中
  const dash = lower.replace(/-/g, ' ').replace(/\s+/g, ' ').trim();
  if (dash !== lower && PHRASE[dash]) return PHRASE[dash];

  // ② 去前缀规则
  for (const [re, fn] of RULES) {
    const m = lower.match(re);
    if (m) {
      const inner = PHRASE[m[1]] || translateWords(m[1]);
      const out = fn([inner]);
      if (out && !/[a-z]/i.test(out)) return out;
    }
  }

  // ③ 贪心多词短语匹配
  const greedy = greedyTranslate(dash);
  if (greedy) return greedy;

  // ④ 词元级翻译
  const out = translateWords(dash);
  return out || en;
}

/** 贪心：从最长短语开始扫描，能命中就替换 */
function greedyTranslate(s) {
  const keys = Object.keys(PHRASE).filter(k => k.includes(' ')).sort((a,b) => b.length - a.length);
  const out = [];
  let rest = s;

  while (rest.length) {
    let matched = false;
    for (const k of keys) {
      // 结尾匹配（rest 恰好等于 k）也要命中，否则 "push up" 永远匹配不上
      if (rest === k) {
        out.push(PHRASE[k]);
        rest = '';
        matched = true;
        break;
      }
      if (rest.startsWith(k + ' ')) {
        out.push(PHRASE[k]);
        rest = rest.slice(k.length + 1);
        matched = true;
        break;
      }
    }
    if (matched) continue;

    // 单个词
    const sp = rest.indexOf(' ');
    const w = sp === -1 ? rest : rest.slice(0, sp);
    const clean = w.replace(/[^a-z0-9]/g, '');
    const t = WORD[w] !== undefined ? WORD[w] : (WORD[clean] !== undefined ? WORD[clean] : undefined);
    if (t === undefined) return null;   // 有生词 → 放弃
    if (t !== '') out.push(t);
    rest = sp === -1 ? '' : rest.slice(sp + 1);
  }
  return out.join('');
}

function translateWords(s) {
  const parts = s.split(/[\s]+/).filter(Boolean);
  const out = [];
  let failed = false;

  for (const p of parts) {
    let w = WORD[p];
    if (w === undefined) {
      // 尝试去掉标点的变体
      w = WORD[p.replace(/[^a-z0-9]/g, '')];
    }
    if (w === undefined) {
      failed = true;
      out.push(p);
    } else if (w !== '') {
      out.push(w);
    }
  }
  const joined = out.join('');
  return failed ? '' : joined;
}

