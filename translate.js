// ─── 特殊符号 / 后缀处理 ───
function cleanName(n) {
  return n
    .replace(/\s*\(male\)/gi, '')
    .replace(/\s*\(female\)/gi, '')
    .replace(/\s*\(with[^)]*\)/gi, '')
    .replace(/\s*\(on [^)]*\)/gi, '')
    .replace(/\s*\(back pov\)/gi, '（后视角）')
    .replace(/\s*\(side pov\)/gi, '（侧视角）')
    .replace(/\s*\(front pov\)/gi, '（前视角）')
    .replace(/\s*\(pov\)/gi, '（视角）')
    .replace(/\s*\(and throw down\)/gi, '（后抛）')
    .replace(/\s*\(with throw down\)/gi, '（后抛）')
    .replace(/\s*\(with lateral throw down\)/gi, '（侧向抛）')
    .replace(/\s*-\s*\(band under both legs\)\s*v\.\s*2/gi, '（弹力带双腿下方·二式）')
    // v. 2 / v.2 / v. 3 → 统一成「2式」「3式」
    .replace(/\s+v\.\s*(\d+)/gi, ' $1式')
    // 去掉剩余修饰性括号（保留有语义的两个）
    .replace(/\s*\((sz-bar|v-bar|narrow parallel grip|cross body|up-down|with arms on chest|hammer grip|palm up)\)/gi, '')
    .replace(/\(\s*\)/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

